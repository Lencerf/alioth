#[derive(Debug, Copy, Clone, PartialEq, Eq, Hash)]
pub enum CpuidReg {
    Eax,
    Ebx,
    Ecx,
    Edx,
}

#[derive(Debug, Copy, Clone, PartialEq, Eq, Hash)]
pub struct FeatureWordInfo {
    pub func: u32,
    pub index: Option<u32>,
    pub reg: CpuidReg,
    pub names: &'static [&'static str; 32],
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CpuFeature {
    pub name: &'static str,
    pub func: u32,
    pub index: Option<u32>,
    pub reg: CpuidReg,
    pub bit: u8,
}

