#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_no_duplicate_names() {
        use std::collections::HashSet;
        let mut names = HashSet::new();
        for info in FEATURE_WORDS {
            for &name in info.names {
                if !name.is_empty() {
                    assert!(names.insert(name), "Duplicate feature name found: {}", name);
                }
            }
        }
    }
}
